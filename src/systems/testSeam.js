export function setTestState(partial) {
  if (!TEST_MODE || !window.__TEST__) {
    return;
  }

  Object.assign(window.__TEST__, partial);
}

export function setTestCommand(name, command) {
  if (!TEST_MODE || !window.__TEST__) {
    return;
  }

  window.__TEST__.commands[name] = command;
}

