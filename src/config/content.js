const makeLessons = (quarterId, majorIndex, topic) => {
  return Array.from({ length: 5 }, (_, index) => ({
    id: `${quarterId}-m${majorIndex + 1}-l${index + 1}`,
    label: `${index + 1}`,
    title: `${topic} ${index + 1}`,
  }));
};

const makeMajor = (quarterId, index, title, icon) => ({
  id: `${quarterId}-major-${index + 1}`,
  title,
  icon,
  lessons: makeLessons(quarterId, index, title),
});

